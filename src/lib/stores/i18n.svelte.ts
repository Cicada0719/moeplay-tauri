let _lang = $state('zh');
// 英文词典懒加载：默认中文界面不下载英文文案（主包减负）。
let enDict: Record<string, string> | null = null;
const strings: Record<string, Record<string, string>> = { zh };

async function loadEn(): Promise<Record<string, string>> {
  if (!enDict) {
    const mod = await import('./i18n.en');
    enDict = mod.en;
  }
  return enDict;
}

export const i18n = {
  get lang() { return _lang; },
  // 兼容旧调用：切英文走异步预载，词典就绪后才真正切换（期间界面保持当前语言）
  set lang(v: string) {
    const next = v === 'en' ? 'en' : 'zh';
    if (next === 'zh') { _lang = 'zh'; localStorage.setItem('moegame-lang', 'zh'); return; }
    void loadEn().then((dict) => {
      strings.en = dict;
      _lang = 'en';
      localStorage.setItem('moegame-lang', 'en');
    });
  },
  /** 异步切换语言：等待词典加载完成后生效（设置页使用） */
  async setLanguage(v: string): Promise<void> {
    const next = v === 'en' ? 'en' : 'zh';
    if (next === 'zh') { _lang = 'zh'; localStorage.setItem('moegame-lang', 'zh'); return; }
    const dict = await loadEn();
    strings.en = dict;
    _lang = 'en';
    localStorage.setItem('moegame-lang', 'en');
  },
  get languages() { return Object.keys(strings); },
  // BCP47 locale，供日期/时间格式化随界面语言联动。
  get locale() { return _lang === 'zh' ? 'zh-CN' : 'en-US'; },

  t(key: string, params?: Record<string, string | number>): string {
    const dict = strings[_lang] ?? strings.zh;
    let text = dict[key] ?? strings.zh[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(`{{k}}`, String(v));
      }
    }
    return text;
  },
};

// 启动时若记忆语言为英文：异步加载词典后切换（加载完成前界面保持中文）
if (typeof localStorage !== 'undefined' && localStorage.getItem('moegame-lang') === 'en') {
  void loadEn().then((dict) => {
    strings.en = dict;
    _lang = 'en';
  });
}


// 启动对齐：仅当 localStorage 没有用户显式选择（moegame-lang 为空）时，
// 首次 settingsStore.load() 完成后用后端 settings.language 兜底一次。
// 对齐走 setter 写入 localStorage，此后语言以用户切换为唯一来源，不再被后端覆盖。
$effect.root(() => {
  $effect(() => {
    if (!settingsStore.loaded) return;
    if (localStorage.getItem("moegame-lang") !== null) return;
    const backendLang = settingsStore.language;
    if (backendLang) i18n.lang = backendLang;
  });
});
